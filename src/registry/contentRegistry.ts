/**
 * Helper to get a registry item by its stable contentId
 */
export function getRegistryItem(contentId: string): ContentRegistryItem | undefined {
  return CONTENT_REGISTRY.find((item) => item.contentId === contentId);
}

/**
 * Helper to get all registry items for a room
 */
export function getRegistryItemsForRoom(roomId: string): ContentRegistryItem[] {
  return CONTENT_REGISTRY.filter((item) => item.roomId === roomId);
}

/**
 * Helper to get all unique rooms from registry
 */
export function getRegistryRooms(): { roomId: string; roomNameVi: string }[] {
  const seen = new Set<string>();
  const list: { roomId: string; roomNameVi: string }[] = [];
  for (const item of CONTENT_REGISTRY) {
    if (!seen.has(item.roomId)) {
      seen.add(item.roomId);
      list.push({ roomId: item.roomId, roomNameVi: item.roomNameVi });
    }
  }
  return list;
}
